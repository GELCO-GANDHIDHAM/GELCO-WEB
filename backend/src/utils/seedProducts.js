const buildUniqueSlug = async (name, model, excludeId = null) => {
  const base = model ? `${name}-${model}` : name;
  let slug = slugify(base);
  let existing = await Product.findOne({ slug, _id: { $ne: excludeId } });
  let counter = 1;
  while (existing) {
    slug = `${slugify(base)}-${counter}`;
    existing = await Product.findOne({ slug, _id: { $ne: excludeId } });
    counter++;
  }
  return slug;
};

const seed = async () => {
  console.log('🌱 Connecting to MongoDB Atlas...');
  await mongoose.connect(process.env.MONGODB_URI);
  console.log('✅ Connected successfully!');

  // Load all categories
  const categories = await Category.find();
  console.log(`📦 Loaded ${categories.length} categories from DB.`);

  const catMap = {};
  for (const c of categories) {
    catMap[c.name.toLowerCase().trim()] = c._id;
  }

  let created = 0;
  let updated = 0;

  for (const item of SAMPLE_PRODUCTS) {
    const catId = catMap[item.categoryName.toLowerCase().trim()];
    if (!catId) {
      console.warn(`⚠️  Category not found for: "${item.categoryName}"`);
      continue;
    }

    const slug = await buildUniqueSlug(item.name, item.model);

    // Check if exists by name
    const existing = await Product.findOne({ name: item.name });
    if (existing) {
      await Product.findByIdAndUpdate(existing._id, {
        model: item.model,
        category: catId,
        shortDescription: item.shortDescription,
        description: item.description,
        features: item.features,
        specifications: item.specifications,
        images: item.images,
        displayOrder: item.displayOrder,
        isActive: true
      });
      updated++;
      console.log(`   🔄 Updated: ${item.name} (${item.model})`);
    } else {
      await Product.create({
        name: item.name,
        model: item.model,
        slug,
        category: catId,
        shortDescription: item.shortDescription,
        description: item.description,
        features: item.features,
        specifications: item.specifications,
        images: item.images,
        displayOrder: item.displayOrder,
        isActive: true
      });
      created++;
      console.log(`   ✔ Created: ${item.name} (${item.model})`);
    }
  }

  console.log(`\n🎉 SEED COMPLETED! Created: ${created}, Updated: ${updated}`);
  const total = await Product.countDocuments();
  console.log(`📊 Total Products now in MongoDB: ${total}`);
  process.exit(0);
};

seed().catch((err) => {
  console.error('❌ Seeding failed:', err);
  process.exit(1);
});
